package com.centsible.backend.statement;

import java.io.IOException;

/**
 * Made-up statements in the same three layouts as the banks Centsible has been checked
 * against: Sampath-style (one heading row, signed amounts, D/C flag, oldest first, no
 * heading repeated on page 2), Seylan-style (heading wrapped over three lines, "LKR" amounts,
 * CR/DR column, newest first, wrapped descriptions, heading repeated on each page) and
 * Commercial-Bank-style (separate Payments / Receipts columns, two dates, opening balance).
 * All names, numbers and amounts are invented.
 */
final class SyntheticStatements {

    private SyntheticStatements() {
    }

    // ---------------------------------------------------------------- Sampath-style

    static byte[] sampathStyle() throws IOException {
        return sampathStyle("95,750.00", "345,750.00", "342,649.50", "292,649.50", "292,803.96");
    }

    /** Same statement with each printed running balance supplied, so a test can corrupt one. */
    static byte[] sampathStyle(String b1, String b2, String b3, String b4, String b5) throws IOException {
        SyntheticStatementPdf pdf = new SyntheticStatementPdf().page();
        pdf.text(84, 129, "Example Bank Internet Banking - Account Statement");
        pdf.text(23, 170, "Name:").text(127, 171, "TEST CUSTOMER ONE");
        pdf.text(23, 215, "Account Number:").text(127, 216, "000000000001");
        pdf.text(23, 238, "Statement Period:").text(127, 238, "01-03-2026 to 31-03-2026");
        pdf.text(23, 283, "Currency:").text(127, 283, "LKR");

        pdf.text(34, 342, "Tran Date").text(200, 342, "Particulars").text(366, 342, "DR/CR")
                .text(439, 342, "Amount").text(502, 342, "Balance");
        sampathRow(pdf, 358, "05-03-2026", "Grocery store", "D", "-4,250.00", b1);
        sampathRow(pdf, 375, "08-03-2026", "Salary March", "C", "250,000.00", b2);
        sampathRow(pdf, 391, "12-03-2026", "Electricity bill", "D", "-3,100.50", b3);
        pdf.text(23, 790, "Example Bank PLC - Company No. 000      Generated: 01/04/2026 10:00:00 AM");

        pdf.page();
        sampathRow(pdf, 30, "20-03-2026", "Transfer to savings", "D", "-50,000.00", b4);
        sampathRow(pdf, 47, "28-03-2026", "Int.Pd:20-02-2026 to 19-03-2026", "C", "154.46", b5);
        pdf.text(23, 790, "Example Bank PLC - Company No. 000      Generated: 01/04/2026 10:00:00 AM");
        return pdf.build();
    }

    private static void sampathRow(SyntheticStatementPdf pdf, float y, String date, String desc,
                                   String flag, String amount, String balance) throws IOException {
        pdf.text(35.5f, y, date).text(94, y, desc).text(379, y, flag)
                .textRight(474, y, amount).textRight(538, y, balance);
    }

    // ---------------------------------------------------------------- Seylan-style

    static byte[] seylanStyle() throws IOException {
        SyntheticStatementPdf pdf = new SyntheticStatementPdf().page();
        pdf.text(431, 26, "Statement of Account");
        pdf.text(326, 49, "Account Number - 000000000002").text(326, 63, "Account Type   - Savings Account");
        pdf.text(16, 113, "Your Account Statement Summary");
        pdf.text(80, 146, "Statement Period").text(275, 146, "Start Balance").text(464, 146, "End Balance");
        pdf.text(65, 160, "2026 Feb 02 to 2026 Feb 28").text(271, 160, "LKR 10,000.00").text(463, 160, "LKR 14,409.90");
        pdf.text(16, 183, "Your Transactions:");
        seylanHeader(pdf);
        seylanRow(pdf, 252.5f, "28/02/2026", "TAX", "", "DR", "LKR 0.60", "LKR 14,409.90");
        seylanRow(pdf, 297.5f, "28/02/2026", "INTEREST", "", "CR", "LKR 6.00", "LKR 14,410.50");
        seylanRow(pdf, 342.5f, "15/02/2026", "TRANSFER", "Funds transfer from savings", "CR", "LKR 5,000.00", "LKR 14,404.50");
        pdf.text(16, 780, "Report generated by Example Bank");

        pdf.page();
        seylanHeader(pdf);
        seylanRow(pdf, 252.5f, "10/02/2026", "DEBIT", "CARD FEES ANNUAL 10-02-2026", "DR", "LKR 600.00", "LKR 9,404.50");
        pdf.text(201, 261.7f, "CARD FEES ANNUAL REF 99887766");
        seylanRow(pdf, 297.5f, "02/02/2026", "TAX", "", "DR", "LKR 0.50", "LKR 10,004.50");
        seylanRow(pdf, 342.5f, "02/02/2026", "INTEREST", "", "CR", "LKR 5.00", "LKR 10,005.00");
        pdf.text(16, 780, "Report generated by Example Bank");
        return pdf.build();
    }

    private static void seylanHeader(SyntheticStatementPdf pdf) {
        pdf.text(16, 221, "Transaction").text(66, 221, "Transaction").text(116, 221, "Transaction")
                .text(201, 221, "Transaction").text(441, 221, "Transaction").text(509, 221, "Running");
        pdf.text(401, 225.4f, "CR/DR");
        pdf.text(16, 230, "Date").text(66, 230, "Value Date").text(116, 230, "Type")
                .text(201, 230, "Description").text(441, 230, "Amount").text(509, 230, "Balance");
    }

    private static void seylanRow(SyntheticStatementPdf pdf, float y, String date, String type, String desc,
                                  String flag, String amount, String balance) {
        pdf.text(16, y, date).text(66, y, date).text(116, y, type);
        if (!desc.isEmpty()) {
            pdf.text(201, y, desc);
        }
        pdf.text(401, y, flag).text(441, y, amount).text(509, y, balance);
    }

    // ---------------------------------------------------------------- Commercial-Bank-style

    static byte[] commercialStyle() throws IOException {
        SyntheticStatementPdf pdf = new SyntheticStatementPdf().page();
        pdf.text(256, 101, "Statement of Account");
        pdf.text(54, 279, "Posting Effective ");
        pdf.text(60, 288, "Date").text(104, 288, "Date");
        pdf.text(193, 283, "Particulars").text(314, 283, "Payments").text(393, 283, "Receipts").text(487, 283, "Balance");
        pdf.text(139, 302, "BALANCE AS OF 31/01/26").textRight(549, 302, "20,000.00");
        commercialRow(pdf, 320, "03 Feb 2026", "01 Feb 2026", "PURCHASE   COFFEE SHOP", 'P', "1,250.00", "18,750.00");
        commercialRow(pdf, 336, "10 Feb 2026", "09 Feb 2026", "PURCHASE   TAXI RIDE", 'P', "800.50", "17,949.50");
        commercialRow(pdf, 352, "28 Feb 2026", "28 Feb 2026", "INTEREST", 'R', "120.25", "18,069.75");
        commercialRow(pdf, 368, "28 Feb 2026", "28 Feb 2026", "ADVANCE INCOME TAX", 'P', "12.03", "18,057.72");
        pdf.text(60, 790, "This is a computer generated statement and does not require a signature.");
        return pdf.build();
    }

    private static void commercialRow(SyntheticStatementPdf pdf, float y, String posted, String effective,
                                      String desc, char column, String amount, String balance) throws IOException {
        pdf.text(45.5f, y, posted).text(92, y, effective).text(140.5f, y, desc);
        pdf.textRight(column == 'P' ? 371 : 445, y, amount);
        pdf.textRight(549, y, balance);
    }

    // ---------------------------------------------------------------- Plain unmarked layout

    /** Date / Description / Amount / Balance with unsigned amounts: direction must come from the balance. */
    static byte[] unmarkedAmounts() throws IOException {
        SyntheticStatementPdf pdf = new SyntheticStatementPdf().page();
        pdf.text(50, 100, "Opening Balance").textRight(500, 100, "1,000.00");
        pdf.text(50, 130, "Date").text(150, 130, "Description").text(380, 130, "Amount").text(470, 130, "Balance");
        pdf.text(50, 150, "01/04/2026").text(150, 150, "Corner shop").textRight(420, 150, "200.00").textRight(510, 150, "800.00");
        pdf.text(50, 166, "02/04/2026").text(150, 166, "Refund").textRight(420, 166, "50.00").textRight(510, 166, "850.00");
        return pdf.build();
    }

    /** A page that holds no text at all, like a scanned statement. */
    static byte[] noText() throws IOException {
        return new SyntheticStatementPdf().page().build();
    }
}
